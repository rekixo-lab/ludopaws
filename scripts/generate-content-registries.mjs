
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE = "com.rekixo.ludopaws";
const generatedHeader = "// AUTO-GENERATED by scripts/generate-content-registries.mjs. Do not edit.\n";
const idPattern = /^[a-z][a-z0-9_]{1,63}$/;
const symbolPattern = /^[A-Z][A-Za-z0-9_]*$/;
const folderPattern = /^[a-z][a-z0-9_]*$/;
const kotlinRoot = "android/app/src/main/java/com/rekixo/ludopaws/";

function validateManifest(manifest) {
  if (manifest.schemaVersion !== 1) throw new Error("Unsupported content manifest schemaVersion");
  const groups = ["characters", "boards", "dice", "boardRenderers", "diceRenderers"];
  for (const group of groups) {
    if (!Array.isArray(manifest[group]) || manifest[group].length === 0) {
      throw new Error("Missing content manifest group: " + group);
    }
    const names = new Set();
    for (const entry of manifest[group]) {
      const id = entry.id ?? entry.key;
      if (!idPattern.test(id || "") || names.has(id)) throw new Error("Invalid/duplicate " + group + " ID: " + id);
      names.add(id);
      if (!folderPattern.test(entry.folder || "")) throw new Error("Invalid " + group + " folder: " + entry.folder);
      for (const field of [entry.definition, entry.renderer, entry.avatar, entry.className].filter(x => x != null)) {
        if (!symbolPattern.test(field)) throw new Error("Invalid Kotlin object: " + field);
      }
    }
  }
  const boardKeys = new Set(manifest.boardRenderers.map(item => item.key));
  const diceKeys = new Set(manifest.diceRenderers.map(item => item.key));
  for (const board of manifest.boards) {
    if (!boardKeys.has(board.rendererKey)) throw new Error("No board renderer for " + board.id);
  }
  for (const dice of manifest.dice) {
    if (!diceKeys.has(dice.rendererKey)) throw new Error("No dice renderer for " + dice.id);
  }
  const ids = new Set(manifest.characters.map(item => item.id));
  for (const character of manifest.characters) {
    const audio = character.audio;
    if (!audio || !["PAW", "HOOF", "WEB"].includes(audio.footstepStyle) ||
        !["MOVE_STEP_DOG", "MOVE_STEP_GOAT", "MOVE_STEP_DUCK", "MOVE_STEP_CAT"].includes(audio.footstepFallback) ||
        (audio.voiceOwner != null && !ids.has(audio.voiceOwner)) ||
        (audio.volume != null && !(audio.volume > 0 && audio.volume <= 1))) {
      throw new Error("Invalid audio profile for " + character.id);
    }
  }
  if (!ids.has("dog") || !ids.has("donkey") ||
      manifest.characters.find(item => item.id === "donkey").audio.voiceOwner != null ||
      manifest.characters.find(item => item.id === "goat_lumi")?.audio.voiceOwner !== "goat") {
    throw new Error("Stable starter/Donkey/Lumi compatibility contract violated");
  }
  if (!manifest.boards.some(item => item.id === "board_classic") ||
      !manifest.dice.some(item => item.id === "dice_classic")) {
    throw new Error("Classic fallback boards and dice required");
  }
  return manifest;
}

function renderGeneratedSources(manifest) {
  validateManifest(manifest);
  const paths = {};
  const contentPkg = (kind, item) => PACKAGE + ".feature." + kind + ".content." + item.folder + ".";
  const p = (subpath) => kotlinRoot + subpath;
  const code = lines => generatedHeader + lines.join("\n") + "\n";
  const charDefinitions = manifest.characters.map(item =>
    "        " + contentPkg("characters", item) + item.definition + ".content,");
  paths[p("feature/characters/domain/catalog/GeneratedCharacterDefinitions.kt")] = code([
    "package " + PACKAGE + ".feature.characters.domain.catalog", "",
    "internal object GeneratedCharacterDefinitions {",
    "    val all = listOf(", ...charDefinitions, "    )", "}",
  ]);
  paths[p("feature/characters/rendering/GeneratedCharacterEntries.kt")] = code([
    "package " + PACKAGE + ".feature.characters.rendering", "",
    "internal object GeneratedCharacterEntries {", "    val all = listOf(",
    ...manifest.characters.map(item => {
      const pkg = contentPkg("characters", item);
      return "        RegisteredCharacter(" + pkg + item.definition + ".content, " +
        pkg + item.renderer + ", " + pkg + item.avatar + "),";
    }), "    )", "}",
  ]);
  paths[p("feature/boards/domain/GeneratedBoardDefinitions.kt")] = code([
    "package " + PACKAGE + ".feature.boards.domain", "",
    "internal object GeneratedBoardDefinitions {", "    val all = listOf(",
    ...manifest.boards.map(item => "        " + contentPkg("boards",item) + item.definition + ".content,"),
    "    )", "}",
  ]);
  paths[p("feature/dice/domain/GeneratedDiceDefinitions.kt")] = code([
    "package " + PACKAGE + ".feature.dice.domain", "",
    "internal object GeneratedDiceDefinitions {", "    val all = listOf(",
    ...manifest.dice.map(item => "        " + contentPkg("dice",item) + item.definition + ".content,"),
    "    )", "}",
  ]);
  paths[p("feature/boards/rendering/GeneratedBoardRendererFactories.kt")] = code([
    "package " + PACKAGE + ".feature.boards.rendering", "",
    "internal object GeneratedBoardRendererFactories {",
    "    val factories: Map<String, () -> BoardRenderer> = mapOf(",
    ...manifest.boardRenderers.map(item =>
      '        "' + item.key + '" to { ' + contentPkg("boards",item) + item.className + "() },"),
    "    )", "}",
  ]);
  paths[p("feature/dice/rendering/GeneratedDiceRendererFactories.kt")] = code([
    "package " + PACKAGE + ".feature.dice.rendering", "",
    "internal object GeneratedDiceRendererFactories {",
    "    val factories: Map<String, (Float) -> DiceRenderer> = mapOf(",
    ...manifest.diceRenderers.map(item =>
      '        "' + item.key + '" to { density -> ' + contentPkg("dice",item) +
      item.className + (item.densityArg ? "(density)" : "()") + " },"),
    "    )", "}",
  ]);
  paths[p("feature/characters/domain/audio/GeneratedCharacterAudioProfiles.kt")] = code([
    "package " + PACKAGE + ".feature.characters.domain.audio", "",
    "import " + PACKAGE + ".core.audio.LudoPawsAudioCatalog", "",
    "internal object GeneratedCharacterAudioProfiles {",
    "    val all: Map<String, LudoPawsCharacterAudioProfile> = listOf(",
    ...manifest.characters.map(item => {
      const audio = item.audio;
      return "        LudoPawsCharacterAudioProfile(" + JSON.stringify(item.id) + ", " +
        (audio.voiceOwner === null ? "null" : JSON.stringify(audio.voiceOwner)) + ", " +
        "LudoPawsFootstepStyle." + audio.footstepStyle + ", " +
        "LudoPawsAudioCatalog.Sfx." + audio.footstepFallback +
        (audio.volume ? ", " + String(audio.volume) + "f" : "") + "),";
    }),
    "    ).associateBy { it.characterId }", "}",
  ]);
  return paths;
}

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(fs.readFileSync(path.join(repoRoot, "content/content-manifest.json"), "utf8"));
const outputFiles = renderGeneratedSources(source);

function validateDeclarations() {
  const checkType = (kind, entry, className) => {
    const folder = path.join(repoRoot, kotlinRoot, "feature",kind,"content",entry.folder);
    if (!fs.existsSync(folder)) throw new Error("Missing content folder: " + folder);
    const sources = fs.readdirSync(folder).filter(file => file.endsWith(".kt"))
      .map(file => fs.readFileSync(path.join(folder, file), "utf8")).join("\n");
    if (!new RegExp("\\b(object|class)\\s+" + className + "\\b").test(sources)) {
      throw new Error("Missing Kotlin declaration " + kind + "/" + entry.folder + "/" + className);
    }
    return sources;
  };
  for (const c of source.characters) {
    const contents = checkType("characters",c,c.definition);
    checkType("characters",c,c.renderer);
    checkType("characters",c,c.avatar);
    if (!contents.includes('"' + c.id + '"')) throw new Error("Character source ID mismatch: " + c.id);
  }
  for (const group of ["boards", "dice"]) {
    for (const entry of source[group]) {
      const contents = checkType(group,entry,entry.definition);
      if (!contents.includes('"' + entry.id + '"')) throw new Error("Content source ID mismatch: " + entry.id);
      if (entry.rendererKey !== "classic" && !contents.includes('"' + entry.rendererKey + '"')) {
        throw new Error("Renderer key mismatch: " + entry.id + " / " + entry.rendererKey);
      }
    }
  }
  for (const entry of source.boardRenderers) checkType("boards",entry,entry.className);
  for (const entry of source.diceRenderers) checkType("dice",entry,entry.className);
}
const command = process.argv[2] || "--check";
if (!["--check", "--write", "--report"].includes(command)) throw new Error("Use --check, --write or --report");
validateDeclarations();
if (command === "--report") {
  console.log(JSON.stringify({characters:source.characters.map(item=>item.id),
    boards:source.boards.map(item=>item.id),dice:source.dice.map(item=>item.id)}, null, 2));
} else {
  for (const [file, expected] of Object.entries(outputFiles)) {
    const target = path.join(repoRoot,file);
    if (command === "--write") {
      fs.mkdirSync(path.dirname(target), {recursive:true});
      fs.writeFileSync(target,expected);
    } else if (!fs.existsSync(target) || fs.readFileSync(target,"utf8") !== expected) {
      throw new Error("Stale generated content registry: " + file + ". Run node scripts/generate-content-registries.mjs --write");
    }
  }
  console.log("Unified content manifest validated: "+source.characters.length+" characters, "+
     source.boards.length+" boards, "+source.dice.length+" dice, "+Object.keys(outputFiles).length+" generated registries.");
}
