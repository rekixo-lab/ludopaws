#!/usr/bin/env python3
"""Reproduce the native launch vector from the pinned first-party Rekixo SVG."""
import argparse
import hashlib
import math
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'branding/rekixo/rekixo-logo-static.svg'
OUTPUT = ROOT / 'android/app/src/main/res/drawable/ic_rekixo_launch.xml'
OUTPUT_V31 = ROOT / 'android/app/src/main/res/drawable-v31/ic_rekixo_launch.xml'
ANDROID = 'http://schemas.android.com/apk/res/android'
AAPT = 'http://schemas.android.com/aapt'
SVG = 'http://www.w3.org/2000/svg'
ET.register_namespace('android', ANDROID)
ET.register_namespace('aapt', AAPT)

def a(name): return '{' + ANDROID + '}' + name

def generate(width=216):
    raw = SOURCE.read_bytes()
    # The vendored file normalizes the upstream redundant final blank line.
    upstream = raw + b'\n'
    blob = hashlib.sha1(b'blob ' + str(len(upstream)).encode() + b'\0' + upstream).hexdigest()
    assert blob == '75d2e1197f8925061ca5b36cf67bac5d5e1dce9a', 'Pinned branding source changed'
    source = ET.fromstring(raw)
    assert source.get('viewBox') == '0 0 1737 402'
    # Android <=30 can show the requested 20% enlargement (180 ->216dp).
    # Android 12+ masks the native icon to a 192dp circle: keep its complete
    # wide wordmark at 187dp, the largest whole-dp width without clipping.
    height = width * 402 / 1737
    assert math.hypot(width / 2, height / 2) < (96 if width == 187 else 144)
    scale = width / 1737
    vector = ET.Element('vector', {a('width'): '288dp', a('height'): '288dp',
        a('viewportWidth'): '288', a('viewportHeight'): '288'})
    host = ET.SubElement(vector, 'group', {a('scaleX'): f'{scale:.10f}',
        a('scaleY'): f'{scale:.10f}', a('translateX'): f'{(288-width)/2:.10f}',
        a('translateY'): f'{(288-height)/2:.10f}'})
    gradients = {g.get('id'): g for g in source.findall('.//{' + SVG + '}linearGradient')}
    logo = source.find(".//{" + SVG + "}g[@id='rekixo-logo']")
    assert logo is not None
    paths = list(logo.iter('{' + SVG + '}path'))
    assert len(paths) == 16
    for path in paths:
        parent = host
        transform = path.get('transform')
        if transform:
            match = re.fullmatch(r'translate\(([-\d.]+)\s+([-\d.]+)\)', transform)
            if not match: raise ValueError('Unsupported SVG transform: ' + transform)
            parent = ET.SubElement(host, 'group', {a('translateX'): match[1], a('translateY'): match[2]})
        attrs = {a('name'): path.get('id'), a('pathData'): ' '.join(path.get('d').split()), a('fillType'): 'evenOdd'}
        if path.get('id').startswith('shine-'):
            # The original stylesheet overrides its group's presentation attribute.
            attrs[a('fillAlpha')] = '0.28'
        dest = ET.SubElement(parent, 'path', attrs)
        gradient_id = re.fullmatch(r'url\(#([\w-]+)\)', path.get('fill', '')).group(1)
        original = gradients[gradient_id]
        item = ET.SubElement(dest, '{' + AAPT + '}attr', {'name': 'android:fillColor'})
        grad = ET.SubElement(item, 'gradient', {a('type'): 'linear', a('startX'): original.get('x1'),
            a('startY'): original.get('y1'), a('endX'): original.get('x2'), a('endY'): original.get('y2')})
        for stop in original:
            rgb = stop.get('stop-color').lstrip('#')
            alpha = round(float(stop.get('stop-opacity', '1')) * 255)
            ET.SubElement(grad, 'item', {a('offset'): stop.get('offset'), a('color'): f'#{alpha:02X}{rgb.upper()}'})
    ET.indent(vector, space='    ')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate-rekixo-launch.py. Original geometry/gradients retained; SVG filter shadow omitted. -->\n'
        + ET.tostring(vector, encoding='unicode') + '\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for destination, width in ((OUTPUT, 216), (OUTPUT_V31, 187)):
        result = generate(width)
        if args.check:
            if not destination.exists() or destination.read_text() != result:
                raise SystemExit('Launch vector is out of date; regenerate it.')
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(result)
    print('Rekixo launch vectors: 216dp on Android <=30; mask-safe 187dp on Android 12+.')
